########################################################
# Predicted_Trait_Analysis.R
#
# Bayesian ANOVA (brms) of spectrally predicted nitrogen and calcium as a
# function of milling x drying treatment, with three nested random
# intercepts: species identity, individual tree within species, and
# measurement (treatment combination) within individual. Coefficients are
# expressed relative to oven-dried, coarse (20-mesh) rotary-milled samples.
#
# Author(s): Mill Test Team
# (2026 cleanup: de-hard-coded paths; nitrogen model raised to iter = 20000
#  to match calcium and the methods; explicit Student-t(3, 0, 2.5) priors on
#  the treatment coefficients; the chlorophyll/lignin/starch/phenolics model
#  fragments -- pasted from another project and non-functional here -- moved
#  to archive/. 2026-09-13: restored the 3-level nested random-effects
#  structure -- (1|Species_Code) + (1|Species_Code:SampleID) +
#  (1|Species_Code:SampleID:measure_id) -- from the actual
#  manuscript-generating copy of this script. The version originally cloned
#  into this repo had a simpler, explicitly-WIP 2-term structure
#  ((1|Species_Code) + (1|Species_Code:measure_id), commented "#to try:...")
#  that was never the manuscript's model; every brms run in this repo before
#  today used it by mistake. This also resolves the individual-vs-measurement
#  random-effect SD mismatch flagged against the methods text since 09-07 --
#  it was a missing model term, not a methods-text imprecision. Both models
#  hit the default max_treedepth = 10 hard on the first corrected run --
#  Rhat/ESS were still clean, but bumped to 12 to clear the warning.)
########################################################

library(tidyverse)
library(brms)
library(MCMCvis)

# --- data location (see README) --------------------------------------------
data_root <- Sys.getenv("MILL24_DATA_ROOT",
                        unset = "/Volumes/Enspec/projects/Mill24")

out_dir <- file.path(data_root, "derived", "anova")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

# --- inputs --------------------------------------------------------------
# NOTE: DimensionsDryTraitPredictions.csv / DryTraits_NM.csv are SpectralPredictR
# outputs (see README). As of 2026-09-11, DimensionsDryTraitPredictions.csv is
# real -- regenerated by running Workflow_Calculations/code/SpectralPredictR.R
# against DrySpec/. DryTraits_NM.csv (used below only for the Sample_ID ->
# Type/Species/Species_Code lookup) is still a placeholder; that script
# doesn't produce it. Re-verify this join once a real DryTraits_NM.csv lands.

traits <- read.csv(file.path(data_root, "spectralpredictr",
                             "DimensionsDryTraitPredictions.csv")) %>%
  distinct()

meta <- read.csv(file.path(data_root, "spectralpredictr", "DryTraits_NM.csv"))
meta_join <- meta %>%
  select(Sample_ID, Type, Species, Species_Code) %>%
  distinct()

# --- assemble the modelling table --------------------------------------

# sampledata_head is e.g. "MILL24_0030_FF_TWEN_00000"
traits_clean <- traits %>%
  separate_wider_delim(
    sampledata_head, delim = "_",
    names = c("Mill", "SampleID", "DryTreat", "MillTreat", "Rep"),
    cols_remove = FALSE
  ) %>%
  mutate(measure_id = paste(Mill, SampleID, DryTreat, MillTreat, sep = "_"),
         SampleID   = paste0("MILL24_", SampleID)) %>%
  select(sampledata_head, measure_id, SampleID, DryTreat, MillTreat,
         t_mean_Nitrogen, t_mean_Calcium) %>%
  left_join(meta_join, by = c("SampleID" = "Sample_ID")) %>%
  # 40/60-mesh -> FINE (conifers only went to 40), 20-mesh -> COARSE
  mutate(MillTreat = case_when(MillTreat == "SIXT" ~ "FINE",
                               MillTreat == "TWEN" ~ "COARSE",
                               TRUE ~ MillTreat)) %>%
  # keep the two well-sampled growth forms; drop the honey-locust extra
  filter(Type %in% c("Conifer", "Broadleaf"), Species_Code != "GLTR") %>%
  # reference level = oven-dried, coarse rotary mill
  mutate(MillTreat = relevel(factor(MillTreat), ref = "COARSE"),
         DryTreat  = relevel(factor(DryTreat),  ref = "OD"))

# --- models ------------------------------------------------------------
# 4 chains, 20,000 iterations, 5,000 warmup (per the manuscript methods).
# Weakly-informative Student-t(3, 0, 2.5) priors on the treatment
# coefficients; brms's own Student-t defaults are kept for the intercept,
# group-level SDs and sigma.

trt_prior <- prior(student_t(3, 0, 2.5), class = "b")

fit_trait <- function(response) {
  brm(
    formula = bf(paste0(response, " ~ MillTreat * DryTreat +",
                        " (1 | Species_Code) + (1 | Species_Code:SampleID) +",
                        " (1 | Species_Code:SampleID:measure_id)")),
    family  = gaussian(),
    data    = traits_clean,
    prior   = trt_prior,
    seed    = 112,
    chains  = 4, cores = 4,
    iter    = 20000, warmup = 5000,
    control = list(max_treedepth = 12)
  )
}

calc_mod <- fit_trait("t_mean_Calcium")
n_mod    <- fit_trait("t_mean_Nitrogen")

# --- outputs ---------------------------------------------------------

coef_labels <- c(
  b_Intercept                  = "Intercept",
  b_MillTreatBALL              = "Ball mill",
  b_MillTreatFINE              = "Fine mesh (40/60)",
  b_DryTreatFF                 = "Freeze-dried",
  `b_MillTreatBALL:DryTreatFF` = "Ball mill / Freeze-dried interaction",
  `b_MillTreatFINE:DryTreatFF` = "Fine mesh / Freeze-dried interaction",
  sd_Species_Code__Intercept                          = "Species random effect s.d.",
  `sd_Species_Code:SampleID__Intercept`               = "Individual (within species) random effect s.d.",
  # measure_id = sample x drying x milling combination, so this level is the
  # tree-by-treatment-combination deviation, shared by that combination's six
  # replicate scans; scan-to-scan variation is the residual (sigma).
  `sd_Species_Code:SampleID:measure_id__Intercept`    = "Tree x treatment combination random effect s.d.",
  sigma                                               = "Residual (scan-to-scan) s.d."
)

report_model <- function(model, tag) {
  print(summary(model))

  saveRDS(model, file.path(out_dir, paste0(tag, "_model.rds")))
  write.csv(posterior_summary(model),
            file.path(out_dir, paste0(tag, "_posterior_summary.csv")))

  MCMCdiag(model, file_name = paste0(tag, "_mod_summary.txt"),
           dir = out_dir, round = 2, open_txt = FALSE)

  pdf(file.path(out_dir, paste0(tag, "_trace.pdf")), width = 8, height = 10)
  plot(model)
  dev.off()

  post <- as.matrix(model)
  keep <- intersect(names(coef_labels), colnames(post))
  jpeg(file.path(out_dir, paste0(tag, "_coefficients_MCMCvis.jpeg")),
       width = 1600, height = 1200, res = 200)
  MCMCplot(post[, keep], labels = unname(coef_labels[keep]),
           xlab = expression("Coefficient or s.d. (mg g"^-1*")"))
  dev.off()
}

report_model(calc_mod, "calcium")
report_model(n_mod,    "nitrogen")
